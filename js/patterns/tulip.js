// y 向上（遠離玩家）為負。flow 0..1 流量，h 0..1 鋼杯高度（高 = 細流，奶沉到咖啡下面，表面不會變白）。
// ease: 進入這個 keyframe 的方式：'smooth'（預設）、'linear'、'step'（瞬間）。
//
// 鬱金香，一次倒完不中斷（D010）：
//   注入（高、細）→ 放低，白色在杯中央浮出 → 推、退、推、退、推、小推 → 拉高一點、往前拉出莖 → 收。
// 倒的過程中流量從不歸零；分層靠「放低推進 / 抬高退回」的節奏（main.js 依高度自動換層）。
// 鋼杯 x 一直是 0（D001），只有前後移動與高度變化。整套往玩家方向偏 0.2，推出去的圖案剛好落在杯子中央。
const K = (t, x, y, flow, h, ease) => ({ t, x, y, flow, h, ease: ease || 'smooth' });
export default {
  id: 'tulip', name: '鬱金香',
  duration: 10.6,
  keyframes: [
    K(0.0, 0.00,  0.25, 0.0, 1.0),
    K(0.7, 0.00,  0.25, 0.0, 1.0),
    K(0.9, 0.00,  0.25, 0.7, 1.0),           // 開始倒：拉高、細流注入，奶沉下去
    K(1.6, 0.10,  0.20, 0.7, 1.0),           // 注入時小幅畫圈
    K(2.3, -0.10,  0.30, 0.7, 1.0),
    K(2.9, 0.00,  0.22, 0.7, 1.0),
    K(3.3, 0.00,  0.06, 1.0, 0.2),           // 放低：白色在中央浮出
    K(4.1, 0.00, -0.08, 1.0, 0.2),           // 第一層：往前推
    K(4.4, 0.00,  0.14, 0.6, 0.62),          // 抬高一點、退回（仍在倒）
    K(4.6, 0.00,  0.16, 1.0, 0.2),           // 放低
    K(5.3, 0.00,  0.04, 1.0, 0.2),           // 第二層
    K(5.6, 0.00,  0.28, 0.6, 0.62),
    K(5.8, 0.00,  0.30, 1.0, 0.2),
    K(6.5, 0.00,  0.18, 1.0, 0.2),           // 第三層
    K(6.8, 0.00,  0.40, 0.6, 0.62),
    K(7.0, 0.00,  0.42, 0.95, 0.24),
    K(7.6, 0.00,  0.34, 0.95, 0.24),         // 第四層（小）
    K(8.1, 0.00,  0.54, 0.5, 0.5),           // 抬高一點、移到圖案後方
    K(9.5, 0.00, -0.28, 0.5, 0.5, 'linear'), // 往前拉穿過所有層，拉出莖
    K(9.9, 0.00, -0.34, 0.0, 1.0),           // 收：拉高、停
    K(10.6, 0.00, -0.36, 0.0, 1.0)
  ]
};
